# Turns the few very detailed flags (coats of arms) into small WebP images so the app stays light.
# Run after tools-flags.mjs:  python3 tools-flags-raster.py
import asyncio, json, re, base64, io
from playwright.async_api import async_playwright
from PIL import Image
src = open('src/flags.js', encoding='utf8').read()
data = json.loads(re.search(r'const FLAGS = (\{.*\});', src, re.S).group(1))
LIMIT = 6 * 1024
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width': 320, 'height': 240})
        n = 0; before = after = 0
        for code, (ar, en, svg) in data.items():
            if len(svg) <= LIMIT: continue
            await pg.set_content(f'<html><body style="margin:0;background:transparent"><img id="f" style="display:block;width:320px;height:240px" src="data:image/svg+xml;base64,{base64.b64encode(svg.encode()).decode()}"></body></html>')
            await pg.wait_for_timeout(60)
            png = await pg.locator('#f').screenshot(omit_background=True)
            im = Image.open(io.BytesIO(png)).convert('RGBA'); buf = io.BytesIO(); im.save(buf, 'WEBP', quality=80, method=6)
            uri = 'data:image/webp;base64,' + base64.b64encode(buf.getvalue()).decode()
            before += len(svg); after += len(uri); data[code][2] = uri; n += 1
        await b.close()
    print(n, 'flags rasterized:', before // 1024, 'KB ->', after // 1024, 'KB')
asyncio.run(main())
total = sum(len(v[2]) for v in data.values())
names = {k: [v[0], v[1]] for k, v in data.items()}
images = {k: v[2] for k, v in data.items()}
open('src/flag-names.js', 'w', encoding='utf8').write('/* generated by tools-flags — country names (ar, en) */\nconst FLAG_NAMES = ' + json.dumps(names, ensure_ascii=False) + ';\n')
open('src/flags.js', 'w', encoding='utf8').write('/* generated by tools-flags from flag-icons (MIT, github.com/lipis/flag-icons) — SVG markup or a WebP data URL */\nconst FLAGS = ' + json.dumps(images, ensure_ascii=False) + ';\n')
print(len(data), 'flags total', total // 1024, 'KB')
