import json, re, sys
sys.path.insert(0, '/home/claude/azwork')
from sources import S, GEN20
d = {c['id']: c for c in json.load(open('/home/claude/azdata/islambook-azkar.json'))}

QREF = re.compile(r'^\s*["“]?(.+?)["”]?\s*\.?\s*\[([^\]\-–]+)[-–]\s*([\d\s،,\-–]+)\]\s*\.?\s*$', re.S)
DIA = re.compile('[ؐ-ًؚ-ٟۖ-ٰۭ]')

def plain(s): return DIA.sub('', s).strip()

def item(cid, i, it, quran=False):
    meta = dict(S.get((cid, i), {}))
    if cid == 20: meta = dict(GEN20)
    t = meta.get('t') or it['t']
    h = ''
    sub = (it.get('sub') or '').strip()
    if sub and t.startswith(sub) and not any(k in plain(sub) for k in ('بسم الله الرحمن', 'أعوذ بالله', 'اللهم')):
        h, t = sub, t[len(sub):].lstrip('\n :')
    t = re.sub(r'[ \t]+\n', '\n', t).strip()
    v = meta.get('v') or (it.get('b') or '').strip()
    src = meta.get('s', '')
    if cid == 21:            # islambook gives the takhrij in this category
        src, v = v, ''
    if quran:
        m = QREF.match(t) if t.count('[') == 1 else None
        if m:
            t = m.group(1).strip().strip('"“” ')
            src = 'القرآن الكريم — سورة ' + plain(m.group(2)).replace('ال', 'ال', 1).strip() + ': ' + re.sub(r'\s+', '', m.group(3))
        else:
            src = 'آيات من القرآن الكريم (المواضع مذكورة في النص)'
        if cid == 28: h = plain(v).rstrip('.'); v = ''
    if not src: raise SystemExit(f'no source for {cid}/{i}: {t[:60]}')
    o = {'t': t, 'c': int(it.get('c') or 1)}
    if h: o['h'] = h
    if v: o['v'] = v
    o['s'] = src
    f = meta.get('f')
    if f: o['f'] = f
    if meta.get('r'): o['w'] = meta['r']
    if meta.get('fix'): o['x'] = meta['fix']
    return o

SETS = {'morning': [(1, i) for i in range(31)], 'evening': [(2, i) for i in range(30)], 'after': [(9, i) for i in range(11)],
        'masjid': [(5, i) for i in range(9)] + [(6, i) for i in range(3)]}
CATS = [(3, 'tasabeeh', 'تسابيح', 'Tasbeeh'), (22, 'salah', 'أذكار الصلاة', 'In the prayer'), (11, 'sleep', 'أذكار النوم', 'Before sleep'),
        (12, 'wake', 'أذكار الاستيقاظ', 'On waking'), (10, 'wudu', 'أذكار الوضوء', 'Wudu'), (4, 'home', 'أذكار المنزل', 'Home'),
        (7, 'khala', 'أذكار الخلاء', 'Restroom'), (13, 'food', 'أذكار الطعام', 'Food'), (14, 'misc', 'أذكار متفرقة', 'Various'),
        (21, 'nabawi', 'أدعية نبوية', 'Prophetic duas'), (15, 'qurani', 'الأدعية القرآنية', 'Quranic duas'), (28, 'anbiya', 'أدعية الأنبياء', 'Duas of the prophets'),
        (27, 'mayyit', 'أدعية للميّت', 'For the deceased'), (20, 'jawami', 'جوامع الدعاء', 'Comprehensive duas'), (16, 'khatm', 'دعاء ختم القرآن', 'Completing the Quran')]

out_sets = {k: [item(c, i, d[c]['items'][i]) for c, i in L] for k, L in SETS.items()}
out_cats = []
for cid, k, ar, en in CATS:
    its = [item(cid, i, it, quran=cid in (15, 28)) for i, it in enumerate(d[cid]['items'])]
    out_cats.append({'k': k, 'ar': ar, 'en': en, 'items': its})

