// Builds src/flags.js: every country flag (ISO 3166-1) as minified SVG + Arabic/English names.
// Source: flag-icons (MIT, https://github.com/lipis/flag-icons). Run: node tools-flags.mjs
import fs from 'node:fs';
import { optimize } from 'svgo';
const dir = 'node_modules/flag-icons/flags/4x3';
const ar = new Intl.DisplayNames(['ar'], { type: 'region' }), en = new Intl.DisplayNames(['en'], { type: 'region' });
const out = {}; let total = 0, n = 0;
for (const f of fs.readdirSync(dir).sort()) {
  const code = f.replace('.svg', '');
  if (!/^[a-z]{2}$/.test(code)) continue;              // countries only (skips arab, eu, un, gb-eng …)
  const C = code.toUpperCase(); let nameEn, nameAr;
  try { nameEn = en.of(C); nameAr = ar.of(C); } catch (e) { continue; }
  if (!nameEn || nameEn === C) continue;
  const svg = optimize(fs.readFileSync(`${dir}/${f}`, 'utf8'), { multipass: true, floatPrecision: 1, plugins: ['preset-default', 'removeDimensions'] }).data;
  if (code === 'ps') nameAr = 'فلسطين';                // common Arabic name
  out[code] = [nameAr, nameEn, svg]; total += svg.length; n++;
}
fs.writeFileSync('src/flags.js', '/* generated by tools-flags.mjs from flag-icons (MIT) */\nconst FLAGS = ' + JSON.stringify(out) + ';\n');
console.log(n, 'flags,', (total / 1024).toFixed(0), 'KB');
